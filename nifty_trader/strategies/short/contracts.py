class TransactionCostConfig(BaseModel):
    """
    Configurable transaction charges for NIFTY Futures backtesting.
    """
    brokerage_per_order: float = 20.0        # ₹20 per executed order (₹40 round-trip)
    exchange_turnover_pct: float = 0.000019   # NSE Futures: 0.0019%
    stt_pct: float = 0.0002                  # STT on sell side: 0.02%
    gst_pct: float = 0.18                    # 18% on (Brokerage + Exchange + SEBI)
    sebi_turnover_pct: float = 0.000001      # SEBI: ₹10 per crore (0.0001%)
    stamp_duty_pct: float = 0.00002          # Stamp duty on entry: 0.002%
    slippage_points: float = 1.0             # 1 point per entry & exit

    def calculate_charges(self, entry_price: float, exit_price: float, quantity: int) -> Dict[str, float]:
        """Calculates itemized Indian market transaction charges for a Futures round-trip."""
        entry_turnover = entry_price * quantity
        exit_turnover = exit_price * quantity
        total_turnover = entry_turnover + exit_turnover

        brokerage = self.brokerage_per_order * 2.0
        exchange = total_turnover * self.exchange_turnover_pct
        stt = entry_turnover * self.stt_pct  # For short position, sell is entry
        sebi = total_turnover * self.sebi_turnover_pct
        gst = (brokerage + exchange + sebi) * self.gst_pct
        stamp = entry_turnover * self.stamp_duty_pct

        total_charges = brokerage + exchange + stt + sebi + gst + stamp
        slippage_cost = 2.0 * self.slippage_points * quantity

        return {
            "brokerage": round(brokerage, 2),
            "exchange": round(exchange, 2),
            "stt": round(stt, 2),
            "sebi": round(sebi, 2),
            "gst": round(gst, 2),
            "stamp_duty": round(stamp, 2),
            "total_charges": round(total_charges, 2),
            "slippage_cost": round(slippage_cost, 2),
        }


class StrategyResult(BaseModel):
    """Evaluation output of the NIFTY Futures Short Strategy."""
    signal: SignalType
    reason: str
    direction: Optional[str] = "SHORT"
    timestamp: datetime
    futures_price: Optional[float] = None
    atm_strike: Optional[float] = None
    ema20: Optional[float] = None
    ema50: Optional[float] = None
    ema20_prev: Optional[float] = None
    atr14: Optional[float] = None
    ema_distance: Optional[float] = None
    oi_resistance: Optional[float] = None
    oi_resistance_strength: Optional[float] = None
    pivot_resistance: Optional[float] = None
    resistance_distance: Optional[float] = None
    trend_bearish: bool = False
    price_below_ema20: bool = False
    ema_distance_ok: bool = False
    resistance_rejection: bool = False
    risk_check_passed: bool = False
    entry_price: Optional[float] = None
    stop_loss: Optional[float] = None
    target: Optional[float] = None
    debug_output: str = ""

    def format_debug_output(self, backtest_info: Optional[Dict[str, Any]] = None) -> str:
        """Renders debug output strictly matching prompt section 28."""
        f_p = f"{self.futures_price:.2f}" if self.futures_price is not None else "N/A"
        atm = f"{self.atm_strike:.0f}" if self.atm_strike is not None else "N/A"
        e20 = f"{self.ema20:.2f}" if self.ema20 is not None else "N/A"
        e50 = f"{self.ema50:.2f}" if self.ema50 is not None else "N/A"
        atr = f"{self.atr14:.2f}" if self.atr14 is not None else "N/A"
        e_dist = f"{self.ema_distance:.2f}" if self.ema_distance is not None else "N/A"
        oi_res = f"{self.oi_resistance:.0f}" if self.oi_resistance is not None else "N/A"
        oi_str = f"{self.oi_resistance_strength:.2f}" if self.oi_resistance_strength is not None else "N/A"
        piv_res = f"{self.pivot_resistance:.2f}" if self.pivot_resistance is not None else "N/A"
        r_dist = f"{self.resistance_distance:.2f}" if self.resistance_distance is not None else "N/A"

        lines = [
            "========================================",
            "NIFTY FUTURES SHORT STRATEGY",
            "========================================",
            f"Futures Price       : {f_p}",
            f"ATM                 : {atm}",
            "",
            f"EMA20               : {e20}",
            f"EMA50               : {e50}",
            f"ATR14               : {atr}",
            f"EMA Distance        : {e_dist}",
            "",
            f"OI Resistance       : {oi_res}",
            f"OI Resistance Strength: {oi_str}",
            "",
            f"Pivot Resistance    : {piv_res}",
            f"Resistance Distance : {r_dist}",
            "",
            f"Bearish Trend       : {str(self.trend_bearish).upper()}",
            f"Price < EMA20       : {str(self.price_below_ema20).upper()}",
            f"EMA Distance OK     : {str(self.ema_distance_ok).upper()}",
            f"Resistance Rejection: {str(self.resistance_rejection).upper()}",
            "",
            f"Risk Check          : {'PASSED' if self.risk_check_passed else 'FAILED'}",
            "",
            "========================================",
            f"FINAL SIGNAL        : {self.signal.value}",
            f"REASON              : {self.reason}",
            "========================================",
        ]

        if backtest_info:
            lines.extend([
                f"Entry Price         : {backtest_info.get('entry_price', 'N/A')}",
                f"Stop Loss           : {backtest_info.get('stop_loss', 'N/A')}",
                f"Target              : {backtest_info.get('target', 'N/A')}",
                f"Exit Price          : {backtest_info.get('exit_price', 'N/A')}",
                f"P&L                 : {backtest_info.get('pnl', 'N/A')}",
            ])

        return "\n".join(lines)


