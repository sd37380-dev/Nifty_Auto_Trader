"""
Contracts and Data Models for NIFTY Futures Short Strategy.

Covers:
- MarketSnapshot: normalized data carrier for Live, Paper, and Backtest modes
- StrategyResult: signal, indicators, confluence state, debug formatting
- TradeLog: complete trade record for backtest and execution
- ShortStrategyConfig & TransactionCostConfig: configurable policy parameters
"""

from datetime import datetime, timezone, timedelta
from enum import Enum
import math
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

try:
    from zoneinfo import ZoneInfo
    IST = ZoneInfo("Asia/Kolkata")
except Exception:
    IST = timezone(timedelta(hours=5, minutes=30), name="IST")


class SignalType(str, Enum):
    """Signals generated by NIFTY Short Strategy."""
    SHORT = "SHORT"
    NO_SIGNAL = "NO_SIGNAL"


