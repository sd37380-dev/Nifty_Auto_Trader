"""
Market Data & Candle Models.

Strict Pydantic models for OHLCV candles, session statuses, data quality metrics,
and market perception events.
"""

from datetime import datetime, timezone, timedelta
from enum import Enum
from typing import Any, Dict, Optional
import uuid
from pydantic import BaseModel, Field, model_validator

try:
    import zoneinfo
    IST = zoneinfo.ZoneInfo("Asia/Kolkata")
except Exception:
    IST = timezone(timedelta(hours=5, minutes=30), name="IST")


class Timeframe(str, Enum):
    """Allowed timeframes for Package 3."""
    H1 = "1h"
    M15 = "15m"


class DataQuality(str, Enum):
    """Integrity and freshness rating of market observation data."""
    VALID = "VALID"
    PARTIAL = "PARTIAL"
    STALE = "STALE"
    INVALID = "INVALID"
    UNAVAILABLE = "UNAVAILABLE"


class MarketSessionStatus(str, Enum):
    """Indian market trading session status for NIFTY."""
    PRE_MARKET = "PRE_MARKET"   # 09:00 - 09:15 IST
    OPEN = "OPEN"               # 09:15 - 15:30 IST
    POST_MARKET = "POST_MARKET" # 15:30 - 16:00 IST
    CLOSED = "CLOSED"           # After 16:00, weekends, holidays


class Candle(BaseModel):
    """
    Deterministic OHLCV Candle Model.
    All internal timestamps are normalized to UTC.
    """
    symbol: str = "NIFTY"
    timeframe: Timeframe
    timestamp: datetime
    open: float
    high: float
    low: float
    close: float
    volume: Optional[float] = None
    is_closed: bool = True
    source: str = "numerical"

    @model_validator(mode="after")
    def validate_ohlc_relationships(self) -> "Candle":
        # Ensure timestamp has timezone awareness (normalize to UTC)
        if self.timestamp.tzinfo is None:
            self.timestamp = self.timestamp.replace(tzinfo=timezone.utc)
        else:
            self.timestamp = self.timestamp.astimezone(timezone.utc)

        # Validate prices are positive
        for name, price in [("open", self.open), ("high", self.high), ("low", self.low), ("close", self.close)]:
            if price < 0:
                raise ValueError(f"Price '{name}' cannot be negative: {price}")

        # Validate High/Low relationships
        max_oc = max(self.open, self.close)
        min_oc = min(self.open, self.close)

        # Allow slight floating point tolerance (1e-6)
        if self.high < (max_oc - 1e-6) or self.high < (self.low - 1e-6):
            raise ValueError(f"High ({self.high}) must be >= max(open={self.open}, close={self.close}, low={self.low})")

        if self.low > (min_oc + 1e-6) or self.low > (self.high + 1e-6):
            raise ValueError(f"Low ({self.low}) must be <= min(open={self.open}, close={self.close}, high={self.high})")

        return self

    @property
    def timestamp_ist(self) -> datetime:
        """Returns the candle timestamp in Asia/Kolkata timezone."""
        return self.timestamp.astimezone(IST)

    @property
    def candle_id(self) -> str:
        """Unique deterministic identifier for caching."""
        return f"{self.symbol}_{self.timeframe.value}_{int(self.timestamp.timestamp())}"


class ObservationEventType(str, Enum):
    """Event types generated by the market observation engine."""
    CANDLE_CLOSED = "CANDLE_CLOSED"
    MARKET_OPENED = "MARKET_OPENED"
    MARKET_CLOSED = "MARKET_CLOSED"
    DATA_UPDATED = "DATA_UPDATED"
    DATA_STALE = "DATA_STALE"
    DATA_ERROR = "DATA_ERROR"
    DATA_MISMATCH = "DATA_MISMATCH"


class ObservationEvent(BaseModel):
    """Event payload emitted when market conditions change."""
    event_id: str = Field(default_factory=lambda: f"evt_{uuid.uuid4().hex[:8]}")
    event_type: ObservationEventType
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    symbol: str = "NIFTY"
    timeframe: Optional[Timeframe] = None
    data: Dict[str, Any] = Field(default_factory=dict)
    message: str = ""
